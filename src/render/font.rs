fn glyph(ch: char) -> &'static [&'static str; 7] {
    let up = ch.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(c, _)| *c == up)
        .or_else(|| GLYPHS.iter().find(|(c, _)| *c == '?'))
        .map(|(_, g)| g)
        .unwrap_or(&GLYPHS[0].1)
}

/// Width of `text` in font pixels (no trailing gap).
pub fn width(text: &str) -> usize {
    let n = text.chars().count();
    if n == 0 {
        0
    } else {
        n * (GLYPH_W + 1) - 1
    }
}

/// Horizontal runs of lit pixels per glyph: `(glyph index, row, first column, run length)`,
/// columns counted from the start of the text.
pub fn runs(text: &str) -> Vec<(usize, usize, usize, usize)> {
    let mut out = Vec::new();
    for (i, ch) in text.chars().enumerate() {
        let g = glyph(ch);
        let x0 = i * (GLYPH_W + 1);
        for (row, line) in g.iter().enumerate() {
            let mut start: Option<usize> = None;
            for (col, px) in line.chars().chain(std::iter::once('.')).enumerate() {
                match (px == '#', start) {
                    (true, None) => start = Some(col),
                    (false, Some(s)) => {
                        out.push((i, row, x0 + s, col - s));
                        start = None;
                    }
                    _ => {}
                }
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_well_formed() {
        for (c, g) in GLYPHS {
            assert!(g.iter().all(|r| r.chars().count() == GLYPH_W), "{c}");
        }
    }

    #[test]
    fn lower_case_and_unknown() {
        assert_eq!(runs("a"), runs("A"));
        assert_eq!(runs("é"), runs("?"));
        assert_eq!(width("AB"), 11);
        assert_eq!(width(""), 0);
    }
}
